## หลักการออกแบบโฟลว์ที่ใช้ได้จริง

- **ทำงานซ้ำได้**: ถ้ารันซ้ำต้องไม่สร้างไฟล์ซ้ำหรือส่งอีเมลซ้ำ ให้ตรวจเงื่อนไขก่อนทำงาน
- **จัดการข้อผิดพลาด**: เพิ่มการลองใหม่ และแยกส่วนที่ล้มเหลวออกจากขั้นตอนหลัก
- **อย่าครอบทับ**: ตั้งชื่อไฟล์ใหม่แล้วตรวจว่ามีไฟล์นั้นอยู่แล้วหรือไม่ หรือสร้างโฟลเดอร์ย่อยตามวันที่
- **มี log**: ให้โฟลว์เขียนบันทึกลงไฟล์หรือชีต เพื่อย้อนดูว่าผ่านอะไรมาแล้ว

