## ตัวอย่าง Schema ที่ใช้ได้จริง

เขียน schema ให้เข้มที่สุดเท่าที่ธุรกิจต้องการ ยิ่งกำหนดชัดเจนเท่าไร ยิ่งตรวจสอบง่าย

```json
{
  "type": "object",
  "additionalProperties": false,
  "required": ["order_id", "channel", "total", "items"],
  "properties": {
    "order_id": { "type": "string", "pattern": "^ORD-[0-9]{6}$" },
    "channel": { "type": "string", "enum": ["web", "store", "marketplace"] },
    "total": { "type": "number", "minimum": 0 },
    "items": {
      "type": "array",
      "minItems": 1,
      "items": {
        "type": "object",
        "required": ["sku", "quantity"],
        "properties": {
          "sku": { "type": "string" },
          "quantity": { "type": "integer", "minimum": 1 }
        }
      }
    }
  }
}
```

ข้อควรระวังคือ `additionalProperties: false` ช่วยกันคีย์เกิน แต่ถ้าโมเดลรุ่นที่ใช้ไม่รองรับคีย์นี้ ให้ตัดออกแล้วคุมด้วยการ validate ฝั่งแอปแทน

## เชื่อมกับโค้ดจริง

