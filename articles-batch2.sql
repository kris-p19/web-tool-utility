## เทียบต้นทุนและความยุ่งยาก

- **Prompt** ใช้เวลาแก้ไม่กี่นาที ไม่มีค่าใช้จ่ายเพิ่ม ยกเว้นโทเคนที่ยาวขึ้นเมื่อต้องแนบตัวอย่าง
- **RAG** ต้องมีขั้นตอนแบ่งเอกสาร สร้างเวกเตอร์ ค้นหา และประเมินคุณภาพ แต่ปรับความรู้ใหม่ได้โดยไม่ต้องฝึกโมเดล
- **Fine-tune** เตรียมชุดข้อมูลยากที่สุด ค่าใช้จ่ายต่อรอบสูง และเมื่อผิดพลาดจะหาสาเหตุยากกว่า เพราะการเปลี่ยน prompt ไม่ได้อธิบายได้ด้วยข้อความ
- **RAG บนโมเดลเล็ก** ช่วยลดต้นทุนต่อคำขอได้มาก เพราะบริบทที่ส่งเข้าไปเป็นข้อความที่ตรวจสอบได้ ไม่ใช่พฤติกรรมที่เรียนมาแบบฝังลึก

