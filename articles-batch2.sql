## ทดสอบก่อนใช้งานจริง

1. ทดสอบกับโฟลเดอร์ทดลองที่มีไฟล์เพียงห้าไฟล์
2. ลองเคสที่มีชื่อไฟล์ซ้ำ มีส่วนขยายต่างกัน และมีไฟล์ที่เปิดไม่ได้
3. ตรวจว่าอีเมลที่ส่งออกถูกคนและโฟลเดอร์ที่ระบุ
4. บันทึกโฟลว์เป็นไฟล์แยกและเก็บสำเนาไว้ เพื่อย้อนกลับเมื่อพัง

