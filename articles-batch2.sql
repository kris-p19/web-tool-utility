## Overlay หาพื้นที่ทับซ้อน

Overlay เปรียบเทียบสองชั้นข้อมูลและได้ผลตามตัวเลือกที่เลือก

- **Intersection** ได้เฉพาะพื้นที่ร่วม ใช้หาจุดที่อยู่ในเขตและใกล้สิ่งก่อสร้าง
- **Union** ได้พื้นที่รวมทั้งหมด ใช้เมื่าต้องการขอบเขตเดียว
- **Difference** ได้ส่วนที่อยู่ในชั้นแรกแต่ไม่อยู่ในชั้นหลัง ใช้หาพื้นที่ที่ยังไม่มีบริการ
- **Symmetrical difference** ได้ส่วนที่มีเฉพาะชั้นเดียว ใช้ตรวจความไม่สอดคล้องระหว่างสองแหล่งข้อมูล

