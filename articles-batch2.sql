- เตรียมโฟลเดอร์ต้นทางและปลายทางให้ชัดเจน เพื่อไม่ให้โฟลว์ไปแตะไฟล์ผิด

## โฟลว์ตัวอย่าง: จัดการภาพจากกล้อง

1. **Trigger**: เมื่อมีไฟล์ใหม่ในโฟลเดอร์ `CameraDrop`
2. **Get files in folder**: ดึงรายการไฟล์ที่ยังไม่ได้ประมวลผล
3. **For each file**: ตั้งชื่อใหม่เป็น `วันที่_ชื่อไฟล์เดิม`
4. **Copy file**: คัดลอกไปยังโฟลเดอร์ปลายทางแยกตามเดือน
5. **Send email**: ส่งรายการไฟล์ที่ประมวลผลแล้วไปยังผู้ใช้
6. **Move file**: ย้ายไฟล์ต้นฉบับเข้าโฟลเดอร์ Processed

