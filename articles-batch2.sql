- ถ้าคำตอบถูกข้อมูลแต่รูปแบบไม่ตรงคาด ให้ปรับ prompt หรือบังคับ schema ก่อน
- ถ้ารูปแบบถูกต้องแล้วแต่ทำซ้ำแล้วหลายรอบยังไม่เสถียร และมีตัวอย่างงานจริงเป็นร้อยๆ ถึงพันเคสแล้ว ค่อยพิจารณา fine-tune
