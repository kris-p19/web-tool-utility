- หน้ารายการที่ต้องการชื่อลูกค้าต้อง join เสมอ ถ้าข้อมูลเยอะจะอ่านช้าลง
- งานรายงานที่ซับซ้อนกลายเป็น SQL ยาวหลายบรรทัดและอ่านไม่ออก
- การเพิ่มคอลัมน์ใหม่ต้องผ่านการเปลี่ยนโครงสร้างเสมอ แม้เป็นค่าที่คำนวณได้

