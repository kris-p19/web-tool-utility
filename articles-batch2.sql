## สามแนวทางตอบคำถามเดียวกัน

- **ปรับ Prompt**: เปลี่ยนคำสั่ง ขยายบริบท เพิ่มตัวอย่าง และกำหนดรูปแบบผลลัพธ์ เหมาะเมื่อปัญหาอยู่ที่ความไม่ชัดเจนของคำสั่ง
- **RAG**: ให้โมเดลอ่านเอกสารที่คัดมาให้ในจุดคำถาม เหมาะเมื่อความรู้เปลี่ยนได้เร็วและต้องอ้างอิงแหล่งที่มา
- **Fine-tune**: ฝึกโมเดลด้วยตัวอย่างของงานจริง เหมาะเมื่อต้องการพฤติกรรมสม่ำเสมอ เช่น โค้ดหรือรูปแบบข้อความเฉพาะ

